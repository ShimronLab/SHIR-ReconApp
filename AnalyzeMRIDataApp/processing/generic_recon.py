"""
Generic fallback reconstruction for UNKNOWN scan types.

Any .dat file whose name does not match a known pattern (fully_sampled /
equispaced / poisson / band_*) lands here instead of failing with
NotImplementedError. The goal is robustness: ALWAYS produce an image,
degrading gracefully through simpler methods and logging every fallback.

Modes (``mode`` argument)
-------------------------
  auto          trajectory JSON found → nufft_json, else → cartesian_rss
  cartesian_rss centred IFFT2 + RSS (delegates to reconstruct_fullysamp)
  nufft_json    adjoint NUFFT with a trajectory JSON + RSS (zero-fill)
  nufft_radial  adjoint NUFFT with a uniform-radial trajectory generated by
                ``bart traj -r`` (numpy formula when BART is unavailable)
  cs_pattern    Cartesian CS: sampling mask extracted from the k-space itself
                (``bart pattern``) → ESPIRiT + PICS L1-wavelet

Fallback chain: any failure in a NUFFT/CS path logs a [WARN] and drops to
cartesian_rss; only if that final path also fails does the exception
propagate to the caller (the worker thread's error handler).

Result dict shapes reuse the existing viewers unchanged:
  * NUFFT / CS paths return the Poisson-zero-fill shape
    (combined_img, kspace_combined, imgs_per_coil, traj_scaled, recon_mode)
    rendered by results_viewer._draw_nufft().
  * cartesian_rss returns reconstruct_fullysamp's dict
    (image_rss, kspace_rss, …) rendered by _draw_fullysamp().
Every dict gains "recon_path": "nufft" | "cs" | "cartesian".
"""

import os
from pathlib import Path
from typing import Any, Callable, Dict, Optional

import numpy as np

from .utils import (
    BartTempDir,
    load_trajectory,
    make_bart_trajectory,
    readcfl,
    run_bart,
    scale_trajectory,
    writecfl,
)


from .utils import ensure_twix_importable as _add_twix_path


def _read_slice_coilfirst(
    dat_path: str,
    log: Callable[[str], None],
    slice_selector_cb: Optional[Callable[[int], int]] = None,
) -> np.ndarray:
    """Read a TWIX file and return one slice as (Ncoils, Nacq, Nread)."""
    _add_twix_path()
    from read_siemens_scans.twix_reading import read_raw_twix_data

    log(f"Reading TWIX data: {Path(dat_path).name}")
    kspace_raw, _ = read_raw_twix_data(str(dat_path), fix_oversampling=False)
    if kspace_raw.ndim == 4:                     # (Nslices, Nacq, Ncoils, Nread)
        n_slices = kspace_raw.shape[0]
        sl = int(slice_selector_cb(n_slices)) if slice_selector_cb else n_slices // 2
        log(f"  Multi-slice scan ({n_slices} slices) — using slice {sl}")
        kspace_raw = kspace_raw[sl]
    if kspace_raw.ndim != 3:
        raise ValueError(f"Unexpected raw k-space ndim {kspace_raw.ndim} "
                         f"(shape {kspace_raw.shape}); expected 3-D or 4-D.")
    return np.moveaxis(kspace_raw, 1, 0)          # (Ncoils, Nacq, Nread)


def _ifft2c(ks: np.ndarray) -> np.ndarray:
    """Centred 2-D IFFT over axes 0, 1 (matches fullysamp_recon._ifft2c)."""
    return np.fft.ifftshift(
        np.fft.ifft2(np.fft.fftshift(ks, axes=(0, 1)), axes=(0, 1)),
        axes=(0, 1),
    )


def _raw_rss_result(
    dat_path: str,
    log: Callable[[str], None],
    slice_selector_cb: Optional[Callable[[int], int]] = None,
) -> Dict[str, Any]:
    """
    Last-resort RSS: a bare centred IFFT2 + RSS on the raw k-space, with NO
    oversampling crop or TSE un-scramble. This can never raise on an exotic
    OS factor, so it guarantees an image even when reconstruct_fullysamp's
    heuristics reject the data (e.g. a non-Cartesian scan with no trajectory).
    """
    kspace_cf = _read_slice_coilfirst(dat_path, log, slice_selector_cb)  # (Nc, Nacq, Nread)
    kspace_3d = np.transpose(kspace_cf, (2, 1, 0)).astype(np.complex64)   # (Nread, Nacq, Ncoils)
    log(f"  Last-resort RSS on raw shape {kspace_3d.shape} "
        "(no OS crop / TSE — image may be uncalibrated).")
    images = _ifft2c(kspace_3d)
    image_rss = np.sqrt(np.sum(np.abs(images) ** 2, axis=2))
    kspace_rss = np.sqrt(np.sum(np.abs(kspace_3d) ** 2, axis=2)).astype(np.float32)
    return {
        "kspace_rss":     kspace_rss,
        "image_rss":      image_rss,
        "image_combined": image_rss,
        "sens_maps":      None,
        "combination":    "rss",
        "recon_path":     "cartesian",
        "params":         {"note": "raw IFFT2+RSS fallback (no OS crop / TSE)"},
    }


def _centered_fft2(img: np.ndarray) -> np.ndarray:
    try:
        import sigpy as sp
        return sp.fft(img, axes=(0, 1), center=True)
    except ImportError:
        return np.fft.fftshift(np.fft.fft2(np.fft.ifftshift(img)))


def _radial_traj_raw(
    n_spokes: int,
    n_read: int,
    log: Callable[[str], None],
) -> np.ndarray:
    """
    Uniform-radial trajectory as an (n_spokes*n_read, 2) array in spoke-major
    order (matching the data-sample order make_bart_trajectory assumes).

    BART path: ``bart traj -r -x{n_read} -y{n_spokes}`` (the reference
    implementation). Fallback: the same uniform half-circle formula in numpy.
    """
    from .recon_backend import use_bart

    if use_bart():
        try:
            with BartTempDir("bart_traj_") as tmp:
                out = os.path.join(tmp, "traj")
                run_bart("traj", "-r", f"-x{n_read}", f"-y{n_spokes}", out)
                traj3 = np.real(readcfl(out))          # (3, n_read, n_spokes)
            kx = traj3[0].T                            # (n_spokes, n_read)
            ky = traj3[1].T
            log(f"  radial trajectory from `bart traj -r` "
                f"({n_spokes} spokes × {n_read} samples)")
            return np.stack([kx.ravel(), ky.ravel()], axis=-1)
        except Exception as exc:
            log(f"  [WARN] bart traj failed ({exc}); using numpy radial formula.")

    angles = np.arange(n_spokes) * np.pi / n_spokes
    radii  = np.arange(n_read) - n_read / 2.0
    kx = radii[None, :] * np.cos(angles[:, None])      # (n_spokes, n_read)
    ky = radii[None, :] * np.sin(angles[:, None])
    log(f"  radial trajectory from numpy formula "
        f"({n_spokes} spokes × {n_read} samples)")
    return np.stack([kx.ravel(), ky.ravel()], axis=-1)


def _nufft_zerofill_result(
    kspace_data: np.ndarray,        # (Ncoils, dim1, dim2)
    traj_raw: np.ndarray,           # (dim1*dim2, 2)
    *,
    grid_size: int,
    crop_size: Optional[int],
    scan_fov_m: float,
    traj_margin: float,
    recon_path: str,
    physical_traj: bool,
    log: Callable[[str], None],
) -> Dict[str, Any]:
    """Adjoint NUFFT → crop → RSS. Mirrors the Poisson zero-fill pipeline."""
    from .recon_backend import active_backend_label, nufft_adjoint_to_cartesian

    _, dim1, dim2 = kspace_data.shape
    bart_traj, pixel_size = make_bart_trajectory(
        traj_raw, dim1, dim2, N_grid=grid_size, margin=traj_margin
    )
    if crop_size:
        crop = int(crop_size)
        log(f"  crop_size={crop} px (user override)")
    elif physical_traj:
        crop = int(round(scan_fov_m / pixel_size))
        log(f"  pixel_size={pixel_size * 1e3:.3f} mm, crop_size={crop} px (auto from FOV)")
    else:
        # Trajectory units are sample indices (radial), not physical m⁻¹ —
        # the Nyquist FOV then spans ~n_read grid pixels.
        crop = min(dim2, grid_size)
        log(f"  crop_size={crop} px (auto: readout length; trajectory units are indices)")
    crop = max(2, min(crop, grid_size))

    log(f"Gridding non-cartesian data ({active_backend_label()})…")
    imgs_per_coil, _cart = nufft_adjoint_to_cartesian(
        bart_traj, kspace_data, grid_size, crop, log=log,
    )
    combined = np.sqrt(np.sum(np.abs(imgs_per_coil) ** 2, axis=-1)).T
    kspace_combined = _centered_fft2(combined)
    log("Zero-fill RSS reconstruction complete.")
    return {
        "traj_scaled":     scale_trajectory(traj_raw),
        "imgs_per_coil":   imgs_per_coil,
        "cart_kspace":     None,
        "sens_maps":       None,
        "combined_img":    combined,
        "kspace_combined": kspace_combined,
        "recon_mode":      "zerofill",
        "recon_path":      recon_path,
        "params": {
            "grid_size":   grid_size,
            "scan_fov_m":  scan_fov_m,
            "traj_margin": traj_margin,
            "pixel_size":  pixel_size,
            "crop_size":   crop,
        },
    }


def _reconstruct_cs_pattern(
    dat_path: str,
    *,
    calib_width: int,
    lambda_wav: float,
    max_iter: int,
    espirit_crop: float = 0.8,
    tse: Optional[bool],
    necho: Optional[int],
    te1: Optional[float],
    teeff: Optional[float],
    log: Callable[[str], None],
    slice_selector_cb: Optional[Callable[[int], int]] = None,
) -> Dict[str, Any]:
    """
    Cartesian CS recon for undersampled unknowns: the sampling mask is derived
    from the k-space itself (``bart pattern``; nonzero test without BART),
    then ESPIRiT + PICS L1-wavelet — the same machinery equispaced_recon uses.
    """
    from .recon_backend import (
        active_backend_label, espirit_maps, pics, use_bart,
    )
    from .utils import crop_readout_oversampling

    kspace_cf = _read_slice_coilfirst(dat_path, log, slice_selector_cb)
    kspace_raw = np.moveaxis(kspace_cf, 0, 1)          # (Nacq, Ncoils, Nread)
    # Readout OS crop is best-effort here: for undersampled data the acquired
    # line count (Nacq) is not the readout matrix size, so the auto-detected
    # factor can be off. Never let it abort the CS recon — proceed uncropped.
    try:
        kspace_raw = crop_readout_oversampling(
            kspace_raw, expected_nx=kspace_raw.shape[0], readout_axis=2, log_fn=log
        )
    except Exception as exc:
        log(f"  [WARN] readout OS crop skipped ({exc}).")

    # Cartesian data → echo-train un-scramble applies (same rule as fullysamp).
    from .tse_reorder import detect_tse_params, unscramble_rows
    _tse = detect_tse_params(dat_path, tse=tse, necho=necho, te1=te1, teeff=teeff)
    if _tse is not None:
        log(f"  TSE detected — un-scrambling echo order (necho={_tse['necho']}).")
        kspace_raw = unscramble_rows(
            kspace_raw, _tse["necho"], _tse["TE1"], _tse["TEeff"], log_fn=log
        )

    kspace_3d = np.transpose(kspace_raw, (2, 0, 1)).astype(np.complex64)
    del kspace_raw                                     # (Nread, Nphase, Ncoils)
    n_read, n_phase, _ = kspace_3d.shape
    k4d = kspace_3d[:, :, np.newaxis, :]

    # ── Sampling mask from the data itself ───────────────────────────────────
    log("Extracting sampling pattern from k-space…")
    try:
        if use_bart():
            with BartTempDir("bart_pattern_") as tmp:
                ksp_cfl  = os.path.join(tmp, "ksp")
                mask_cfl = os.path.join(tmp, "mask")
                writecfl(ksp_cfl, k4d)
                run_bart("pattern", ksp_cfl, mask_cfl)
                mask = np.abs(np.squeeze(readcfl(mask_cfl))) > 0
        else:
            mask = (np.abs(kspace_3d) != 0).any(axis=-1)
    except Exception as exc:
        log(f"  [WARN] pattern extraction failed ({exc}); using nonzero test.")
        mask = (np.abs(kspace_3d) != 0).any(axis=-1)
    n_sampled = int(mask.sum())
    total = mask.size
    r_est = total / max(n_sampled, 1)
    log(f"  sampled {n_sampled}/{total} k-space points (R≈{r_est:.2f}×)")
    if r_est < 1.05:
        log("  [NOTE] k-space looks fully sampled — CS will behave like SENSE.")

    # ── Normalise → ESPIRiT → PICS L1-wavelet ────────────────────────────────
    try:
        import sigpy as sp
        img_tmp = sp.rss(sp.ifft(k4d, axes=(0, 1)), axes=-1)
        scale = np.percentile(np.abs(img_tmp).ravel(), 95)
        k4d_norm = k4d / (scale + 1e-12)
    except ImportError:
        k4d_norm = k4d / (np.max(np.abs(k4d)) + 1e-12)

    log(f"Computing ESPIRiT sensitivity maps (calib={calib_width})…")
    sens_maps = espirit_maps(k4d_norm, calib_width, num_maps=1,
                             crop=espirit_crop, log=log)
    log(f"Running CS PICS (λ_wav={lambda_wav}, iters={max_iter}, "
        f"{active_backend_label()})…")
    combined = np.abs(np.squeeze(pics(
        k4d_norm, sens_maps, soft_sense=True, reg="W",
        lam=lambda_wav, iters=max_iter, log=log,
    )))
    kspace_combined = _centered_fft2(combined)
    log("CS (pattern-mask) reconstruction complete.")
    return {
        "imgs_per_coil":   None,
        "cart_kspace":     None,
        "sens_maps":       sens_maps,
        "combined_img":    combined,
        "kspace_combined": kspace_combined,
        "recon_mode":      "pics",
        "recon_path":      "cs",
        "params": {
            "calib_width": calib_width,
            "lambda_wav":  lambda_wav,
            "max_iter":    max_iter,
            "r_estimated": r_est,
        },
    }


def reconstruct_generic(
    dat_path: str,
    *,
    json_path: Optional[str] = None,
    mode: str = "auto",
    grid_size: int = 512,
    calib_width: int = 24,
    scan_fov_m: float = 256e-3,
    crop_size: Optional[int] = None,
    traj_margin: float = 1.0,
    espirit_crop: float = 0.8,      # ESPIRiT eigenvalue mask threshold (both engines)
    lambda_wav: float = 0.01,
    max_iter: int = 100,
    tse: Optional[bool] = None,
    necho: Optional[int] = None,
    te1: Optional[float] = None,
    teeff: Optional[float] = None,
    progress_cb: Optional[Callable[[str], None]] = None,
    slice_selector_cb: Optional[Callable[[int], int]] = None,
) -> Dict[str, Any]:
    """
    Reconstruct a scan of unknown type; see module docstring for the modes.

    Never raises from the NUFFT/CS branches — they fall back to Cartesian
    IFFT + RSS with a [WARN] log line. Only the final Cartesian fallback may
    raise.
    """

    def log(msg: str) -> None:
        if progress_cb:
            progress_cb(msg)

    mode = (mode or "auto").lower()
    if mode == "auto":
        mode = "nufft_json" if (json_path and Path(json_path).exists()) else "cartesian_rss"
        log(f"  Unknown-scan mode 'auto' → {mode}")

    # ── NUFFT with a trajectory JSON ─────────────────────────────────────────
    if mode == "nufft_json":
        try:
            if not (json_path and Path(json_path).exists()):
                raise FileNotFoundError(
                    "no trajectory JSON found — place a <scanname>.json or "
                    "Trajectory.json next to the .dat (or pick one via "
                    "right-click → Choose trajectory JSON…)"
                )
            kspace_data = _read_slice_coilfirst(dat_path, log, slice_selector_cb)
            _, dim1, dim2 = kspace_data.shape
            log(f"  k-space shape (coils, dim1, dim2): {kspace_data.shape}")
            # NUFFT pairs each sample with its JSON coordinate in acquisition
            # order, so no TSE echo un-scramble (same rule as the Poisson recon).
            log(f"Loading trajectory JSON: {Path(json_path).name} (idx=0)…")
            traj_raw = load_trajectory(json_path, "0")
            if len(traj_raw) != dim1 * dim2:
                raise ValueError(
                    f"trajectory length ({len(traj_raw)}) ≠ dim1*dim2 "
                    f"({dim1}*{dim2}={dim1 * dim2}) — the JSON and the .dat "
                    f"were not acquired together"
                )
            return _nufft_zerofill_result(
                kspace_data, traj_raw,
                grid_size=grid_size, crop_size=crop_size,
                scan_fov_m=scan_fov_m, traj_margin=traj_margin,
                recon_path="nufft", physical_traj=True, log=log,
            )
        except Exception as exc:
            log(f"  [WARN] NUFFT (trajectory JSON) failed: {exc}")
            log("  Falling back to Cartesian IFFT + RSS.")
            mode = "cartesian_rss"

    # ── NUFFT with a generated uniform-radial trajectory ─────────────────────
    if mode == "nufft_radial":
        try:
            kspace_data = _read_slice_coilfirst(dat_path, log, slice_selector_cb)
            _, dim1, dim2 = kspace_data.shape
            log(f"  k-space shape (coils, spokes, samples): {kspace_data.shape}")
            log("  Assuming UNIFORM radial ordering (bart traj -r convention); "
                "golden-angle or interleaved radial will look streaky.")
            traj_raw = _radial_traj_raw(dim1, dim2, log)
            return _nufft_zerofill_result(
                kspace_data, traj_raw,
                grid_size=grid_size, crop_size=crop_size,
                scan_fov_m=scan_fov_m, traj_margin=traj_margin,
                recon_path="nufft", physical_traj=False, log=log,
            )
        except Exception as exc:
            log(f"  [WARN] NUFFT (radial) failed: {exc}")
            log("  Falling back to Cartesian IFFT + RSS.")
            mode = "cartesian_rss"

    # ── Cartesian CS with mask extracted from the data ───────────────────────
    if mode == "cs_pattern":
        try:
            return _reconstruct_cs_pattern(
                dat_path,
                calib_width=calib_width, lambda_wav=lambda_wav,
                max_iter=max_iter, espirit_crop=espirit_crop,
                tse=tse, necho=necho, te1=te1, teeff=teeff,
                log=log, slice_selector_cb=slice_selector_cb,
            )
        except Exception as exc:
            log(f"  [WARN] CS (pattern mask) failed: {exc}")
            log("  Falling back to Cartesian IFFT + RSS.")
            mode = "cartesian_rss"

    # ── Cartesian IFFT + RSS (final fallback) ────────────────────────────────
    if not (json_path and Path(json_path).exists()):
        log("  [WARN] No trajectory JSON — assuming Cartesian sampling. "
            "If this scan is non-Cartesian the image will be uninterpretable.")
    from .fullysamp_recon import reconstruct_fullysamp
    try:
        result = reconstruct_fullysamp(
            dat_path, use_sense=False,
            tse=tse, necho=necho, te1=te1, teeff=teeff,
            progress_cb=progress_cb, slice_selector_cb=slice_selector_cb,
        )
        result["recon_path"] = "cartesian"
        return result
    except Exception as exc:
        # OS-crop / TSE heuristics can misfire on exotic scans (e.g. a
        # non-Cartesian scan whose "readout" oversampling looks like factor 4).
        # Retry once with TSE disabled, then fall to the bare raw RSS which
        # never raises — so an unknown scan always yields an image.
        log(f"  [WARN] Cartesian RSS failed ({exc}); retrying with tse=False…")
    try:
        result = reconstruct_fullysamp(
            dat_path, use_sense=False, tse=False,
            progress_cb=progress_cb, slice_selector_cb=slice_selector_cb,
        )
        result["recon_path"] = "cartesian"
        return result
    except Exception as exc:
        log(f"  [WARN] Cartesian RSS still failed ({exc}); "
            "using last-resort raw IFFT2 + RSS.")
    return _raw_rss_result(dat_path, log, slice_selector_cb)
